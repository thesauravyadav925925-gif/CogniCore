/**
 * ACTION EXECUTION WITH HUMAN APPROVAL (Feature 34, Level 3 "approval workflows")
 *   Analyze -> Decide -> Act, but never silently:
 *     propose  (analyst+)  ->  pending
 *     approve  (manager/admin, normally NOT the proposer)  ->  executed | failed
 *     reject   ->  rejected
 * Only a fixed whitelist of action types exists; each validates its parameters and
 * runs with the PROPOSER's data permissions (an approver cannot widen what data an
 * action can read). Everything is audit-logged.
 */
const { getRegistryDb } = require('../config/registry.db');
const { v4: uuidv4 } = require('uuid');

const DDL = `
  CREATE TABLE IF NOT EXISTS action_requests (
    action_id TEXT PRIMARY KEY,
    type TEXT NOT NULL,
    params_json TEXT NOT NULL,
    summary TEXT,
    status TEXT NOT NULL,             -- pending | approved | rejected | executed | failed
    requested_by TEXT NOT NULL,
    decided_by TEXT,
    decision_note TEXT,
    result_json TEXT,
    created_at TEXT NOT NULL,
    decided_at TEXT
  );
  CREATE INDEX IF NOT EXISTS idx_action_status ON action_requests(status);
  CREATE TABLE IF NOT EXISTS action_outbox (
    id TEXT PRIMARY KEY,
    action_id TEXT,
    to_addr TEXT,
    subject TEXT,
    body TEXT,
    attachment_name TEXT,
    delivery TEXT,                    -- smtp | simulated
    created_at TEXT NOT NULL
  );
`;
const getDb = () => getRegistryDb('actions', (d) => d.exec(DDL));

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const now = () => new Date().toISOString();

const TYPES = {
  send_email: {
    label: 'Send email',
    validate(p) {
      const to = (Array.isArray(p.to) ? p.to : [p.to]).filter(Boolean).map((x) => String(x).trim().toLowerCase());
      if (!to.length || to.length > 10 || !to.every((e) => EMAIL_RE.test(e))) throw new Error('"to" must contain 1–10 valid email addresses.');
      const allowed = (process.env.ACTION_EMAIL_ALLOWED_DOMAINS || '').split(',').map((s) => s.trim().toLowerCase()).filter(Boolean);
      if (allowed.length && !to.every((e) => allowed.includes(e.split('@')[1]))) throw new Error(`Recipients must be in: ${allowed.join(', ')}.`);
      const attach = p.attach ? { kind: 'management_report', datasetId: String(p.attach.datasetId || ''), format: ['pdf', 'docx', 'xlsx'].includes(p.attach.format) ? p.attach.format : 'pdf' } : null;
      if (attach && !attach.datasetId) throw new Error('attach.datasetId is required to attach a report.');
      return { to, subject: String(p.subject || 'CogniCore report').slice(0, 200), body: String(p.body || 'Please find the attached report generated by CogniCore.').slice(0, 5000), attach };
    },
    describe: (p) => `Email ${p.to.join(', ')} — "${p.subject}"${p.attach ? ` with a ${p.attach.format.toUpperCase()} management report attached` : ''}`,
  },
  save_report: {
    label: 'Save management report to the server',
    validate(p) {
      const datasetId = String(p.datasetId || '');
      if (!datasetId) throw new Error('datasetId is required.');
      return { datasetId, format: ['pdf', 'docx', 'xlsx'].includes(p.format) ? p.format : 'pdf' };
    },
    describe: (p) => `Generate a ${p.format.toUpperCase()} management report for dataset ${p.datasetId} and store it in the exports folder`,
  },
  webhook: {
    label: 'Call an approved webhook',
    validate(p) {
      let u;
      try { u = new URL(String(p.url)); } catch (_) { throw new Error('url must be a valid URL.'); }
      const allow = (process.env.ACTION_WEBHOOK_ALLOWLIST || '').split(',').map((s) => s.trim().toLowerCase()).filter(Boolean);
      if (!allow.length) throw new Error('No webhooks are approved on this server (set ACTION_WEBHOOK_ALLOWLIST).');
      if (u.protocol !== 'https:' || !allow.includes(u.host.toLowerCase())) throw new Error(`Webhook host must be one of: ${allow.join(', ')} (https only).`);
      return { url: u.toString(), payload: p.payload && typeof p.payload === 'object' ? p.payload : {} };
    },
    describe: (p) => `POST a JSON payload to ${new URL(p.url).host}`,
  },
};

const rowToAction = (r) => r && ({ ...r, params: JSON.parse(r.params_json), result: r.result_json ? JSON.parse(r.result_json) : null, params_json: undefined, result_json: undefined });

const ActionRegistry = {
  TYPES: Object.keys(TYPES),
  describeTypes: () => Object.entries(TYPES).map(([type, t]) => ({ type, label: t.label })),

  propose({ type, params, requestedBy }) {
    const t = TYPES[type];
    if (!t) throw new Error(`Unknown action type "${type}". Allowed: ${Object.keys(TYPES).join(', ')}.`);
    const clean = t.validate(params || {});
    const id = 'act_' + uuidv4().slice(0, 8);
    getDb().prepare(`INSERT INTO action_requests (action_id, type, params_json, summary, status, requested_by, created_at) VALUES (?,?,?,?,?,?,?)`)
      .run(id, type, JSON.stringify(clean), t.describe(clean), 'pending', requestedBy, now());
    return this.get(id);
  },
  get(id) { return rowToAction(getDb().prepare(`SELECT * FROM action_requests WHERE action_id = ?`).get(id)); },
  list({ status = null, requestedBy = null, limit = 100 } = {}) {
    let q = `SELECT * FROM action_requests WHERE 1=1`; const a = [];
    if (status) { q += ` AND status = ?`; a.push(status); }
    if (requestedBy) { q += ` AND requested_by = ?`; a.push(requestedBy); }
    q += ` ORDER BY created_at DESC LIMIT ?`; a.push(limit);
    return getDb().prepare(q).all(...a).map(rowToAction);
  },
  markDecision(id, { status, decidedBy, note = null, result = null }) {
    getDb().prepare(`UPDATE action_requests SET status = ?, decided_by = ?, decision_note = ?, result_json = ?, decided_at = ? WHERE action_id = ?`)
      .run(status, decidedBy, note, result ? JSON.stringify(result) : null, now(), id);
    return this.get(id);
  },
  recordOutbox({ actionId, to, subject, body, attachmentName, delivery }) {
    getDb().prepare(`INSERT INTO action_outbox VALUES (?,?,?,?,?,?,?,?)`).run(uuidv4(), actionId, to, subject, body, attachmentName || null, delivery, now());
  },
  listOutbox(actionId) { return getDb().prepare(`SELECT * FROM action_outbox WHERE action_id = ? ORDER BY created_at`).all(actionId); },
  TYPES_IMPL: TYPES,
};

module.exports = { ActionRegistry, EMAIL_RE };
